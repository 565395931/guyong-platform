const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const FileEventStore = require('../src/gateway/fileEventStore')

test('purging one account preserves others and repairs sequence/cursor before next append', t => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'shop-outbox-delete-'))
  t.after(() => fs.rmSync(directory, { recursive: true, force: true }))
  const store = new FileEventStore(path.join(directory, 'events.json'))
  for (const [eventId, accountId] of [['removed', 1], ['retained', 2]]) store.appendEvent({ eventId, type: 'message.created', payload: { accountId } })
  store.markAttempt('removed'); store.deadLetter('removed', 'fixture')
  store.acknowledge('retained', 'processed')
  store.putCommand('remove-command', { payload: { accountId: 1 } })
  store.putCommand('keep-command', { payload: { accountId: 2 } })
  store.purgeAccount(1)
  assert.equal(store.getCursor(), 1); assert.equal(store.getEvent('retained').sequence, 1)
  assert.equal(store.getEvent('removed'), null); assert.equal(store.getCommand('remove-command'), null)
  assert.equal(store.getCommand('keep-command').payload.accountId, 2)
  assert.equal(store.stats().deliveryAttempts, 0); assert.equal(store.stats().deadLetters, 0)
  assert.equal(store.appendEvent({ eventId: 'next', type: 'message.created', payload: { accountId: 2 } }).sequence, 2)
  assert.equal(new FileEventStore(store.filePath).listPending()[0].eventId, 'next')
})
