const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { FileSaasStore } = require('../src/saas/fileSaasStore')
const { LocalWorkbenchPairing } = require('../src/saas/localWorkbenchPairing')
const http = require('node:http')
const { signSession } = require('../src/saas/security')
const { createControlPlane } = require('../src/saas/controlPlaneServer')
async function fixture(t) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'local-pairing-'))
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }))
  const store = new FileSaasStore(path.join(dir, 'data.json'))
  await store.transaction(data => {
    data.tenants.push({ id: 'a', status: 'active' }, { id: 'b', status: 'active' })
    data.shopInstallations.push({ id: 'shop-a', tenantId: 'a', name: '成长资料铺', appId: 'wx-a', appSecretEncrypted: 'secret-hidden' }, { id: 'shop-a2', tenantId: 'a', name: '正式店铺' }, { id: 'shop-b', tenantId: 'b', name: '其他客户' })
  })
  let now = 1000000
  const pairing = new LocalWorkbenchPairing({ store, now: () => now })
  return { store, pairing, clock: value => { now = value } }
}

test('single-shop detach preserves other bindings/history, is retryable, and revokes final binding', async t => {
  const f = await fixture(t)
  const issued = await f.pairing.issue({ tenantId: 'a' })
  const paired = await f.pairing.exchange({ code: issued.code })
  await f.pairing.bind(paired.token, [{ accountId: 1, gatewayAccountId: 'shop-a' }, { accountId: 2, gatewayAccountId: 'shop-a2' }])
  await f.store.transaction(data => data.messages.push({ id: 'retained', installationId: 'shop-a' }))
  await assert.rejects(f.pairing.detach(paired.client.id, 'shop-b'), { code: 'local_client_unauthorized' })
  await f.pairing.detach(paired.client.id, 'shop-a')
  await f.pairing.detach(paired.client.id, 'shop-a')
  assert.deepEqual((await f.pairing.discovery(paired.token)).shops.map(row => row.gatewayAccountId), ['shop-a2'])
  assert.equal((await f.store.snapshot()).messages.length, 1)
  await f.pairing.detach(paired.client.id, 'shop-a2')
  assert.equal(await f.pairing.authenticate(paired.token), null)
})
test('pairing code is one-use, hashed at rest; discovery never returns another customer or secrets', async t => {
  const f = await fixture(t)
  const issued = await f.pairing.issue({ tenantId: 'a', installationIds: ['shop-a'], actorId: 'admin' })
  const results = await Promise.allSettled([1, 2].map(() => f.pairing.exchange({ code: issued.code })))
  assert.equal(results.filter(row => row.status === 'fulfilled').length, 1)
  const exchanged = results.find(row => row.status === 'fulfilled').value
  const discovery = await f.pairing.discovery(exchanged.token)
  assert.deepEqual(discovery.shops.map(shop => shop.name), ['成长资料铺'])
  assert.equal(JSON.stringify(discovery).includes('secret-hidden'), false)
  const persisted = JSON.stringify(await f.store.snapshot())
  assert.equal(persisted.includes(issued.code), false)
  assert.equal(persisted.includes(exchanged.token), false)
  await f.pairing.revoke(exchanged.client.id, 'a', 'admin')
  assert.equal(await f.pairing.authenticate(exchanged.token), null)
})
test('new code invalidates old code and expires after five minutes', async t => {
  const f = await fixture(t)
  const old = await f.pairing.issue({ tenantId: 'a' })
  const current = await f.pairing.issue({ tenantId: 'a' })
  await assert.rejects(f.pairing.exchange({ code: old.code }), { code: 'local_pairing_rejected' })
  f.clock(1300000)
  await assert.rejects(f.pairing.exchange({ code: current.code }), { code: 'local_pairing_rejected' })
})
test('whole-customer discovery includes newly registered shops but rejects crossed scopes and credit tokens', async t => {
  const f = await fixture(t)
  await assert.rejects(f.pairing.issue({ tenantId: 'a', installationIds: ['shop-b'] }), { code: 'local_pairing_invalid_scope' })
  const issued = await f.pairing.issue({ tenantId: 'a' })
  const exchanged = await f.pairing.exchange({ code: issued.code })
  await f.store.transaction(data => data.shopInstallations.push({ id: 'new-shop', tenantId: 'a', name: '新店' }))
  assert.equal((await f.pairing.discovery(exchanged.token)).shops.length, 3)
  assert.equal(await f.pairing.authenticate('credit-device-token'), null)
  await f.store.transaction(data => { data.tenants[0].status = 'disabled' })
  assert.equal(await f.pairing.authenticate(exchanged.token), null)
})

test('HTTP pairing requires a scoped browser session; anonymous exchange/discovery expose no secrets', async t => {
  const f = await fixture(t)
  const secret = 'test-session-secret-only-for-pairing'
  const control = createControlPlane({ store: f.store, env: { CONTROL_PLANE_ADMIN_PASSWORD: 'mock-password-not-for-production', CONTROL_PLANE_SESSION_SECRET: secret } })
  await control.ready
  const server = http.createServer(control.handler)
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
  t.after(() => new Promise(resolve => server.close(resolve)))
  const url = `http://127.0.0.1:${server.address().port}`
  const request = (path, body, headers = {}) => fetch(url + path, { method: body ? 'POST' : 'GET', headers: { 'content-type': 'application/json', ...headers }, ...(body ? { body: JSON.stringify(body) } : {}) })
  assert.equal((await request('/v1/admin/local-pairings', { tenantId: 'a' })).status, 401)
  const cookie = 'lw_session=' + signSession({ id: 'tenant-admin', role: 'tenant_admin', tenantId: 'a' }, secret)
  assert.equal((await request('/v1/admin/local-pairings', { tenantId: 'a' }, { cookie })).status, 403)
  assert.equal((await request('/v1/account/local-pairings', {}, { cookie, origin: 'https://untrusted.example' })).status, 403)
  const issue = await request('/v1/account/local-pairings', { tenantId: 'b', installationIds: ['shop-a'] }, { cookie })
  assert.equal(issue.status, 201)
  const code = (await issue.json()).data.code
  const exchange = await request('/v1/local-shop/pair', { code, name: '测试本地端' })
  assert.equal(exchange.status, 201)
  const client = (await exchange.json()).data
  assert.equal(client.client.tenantId, 'a')
  assert.equal((await request('/v1/local-shop/pair', { code })).status, 401)
  assert.equal((await request('/v1/local-shop/discovery')).status, 401)
  const discovery = await request('/v1/local-shop/discovery', null, { authorization: 'Bearer ' + client.token })
  assert.equal(discovery.status, 200)
  assert.deepEqual((await discovery.json()).data.shops.map(shop => shop.gatewayAccountId), ['shop-a'])
  assert.equal((await request('/v1/local-shop/detach', { installationId: 'shop-a' })).status, 401)
  assert.equal((await request('/v1/local-shop/detach', { installationId: 'shop-b' }, { authorization: 'Bearer ' + client.token })).status, 403)
  assert.equal((await request('/v1/admin/shops/shop-a/delete', { confirmName: '成长资料铺' })).status, 401)
  assert.equal((await request('/v1/admin/shops/shop-a/delete', { confirmName: '成长资料铺' }, { cookie })).status, 403)
  const adminCookie = 'lw_session=' + signSession({ id: 'operator', role: 'operator' }, secret)
  assert.equal((await request('/v1/admin/shops/shop-a/delete', { confirmName: '成长资料铺' }, { cookie: adminCookie, origin: 'https://untrusted.example' })).status, 403)
  const revoke = await request(`/v1/account/local-clients/${client.client.id}/revoke`, { tenantId: 'b' }, { cookie })
  assert.equal(revoke.status, 200)
  assert.equal((await request('/v1/local-shop/discovery', null, { authorization: 'Bearer ' + client.token })).status, 401)
})
